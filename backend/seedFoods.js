async function seedFoods() {
  const foodsRef = db.collection('foods');

  // Check if already seeded
  const existing = await foodsRef.limit(1).get();
  if (!existing.empty) {
    console.log('⚠️  foods collection already has data. To re-seed, delete the collection first.');
    process.exit(0);
  }

  // Firestore batch limit is 500 — our list is well under that
  const batch = db.batch();

  for (const food of foods) {
    const docRef = foodsRef.doc();
    batch.set(docRef, { ...food, createdAt: new Date().toISOString() });
  }

  await batch.commit();
  console.log(`✅  Seeded ${foods.length} foods to Firestore.`);
  process.exit(0);
}

seedFoods().catch((err) => {
  console.error('❌  Seed failed:', err.message);
  process.exit(1);
});
